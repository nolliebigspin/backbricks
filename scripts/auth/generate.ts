import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const authPackage = join(root, 'packages/auth');
const output = join(root, 'packages/db/src/schema/auth.generated.ts');
const temporary = mkdtempSync(join(tmpdir(), 'bb-auth-schema-'));

try {
  const generated = join(temporary, 'auth.ts');
  const cli = Bun.spawn(
    [
      process.execPath,
      '--no-env-file',
      '--bun',
      'run',
      'auth',
      'generate',
      '--config',
      './auth.config.ts',
      '--adapter',
      'drizzle',
      '--dialect',
      'postgresql',
      '--output',
      generated,
      '--yes',
    ],
    { cwd: authPackage, stdout: 'inherit', stderr: 'inherit' },
  );
  if ((await cli.exited) !== 0) throw new Error('Auth schema generation failed.');
  const source = readFileSync(generated, 'utf8').replace(
    'import { relations } from "drizzle-orm";',
    'import { relations } from "drizzle-orm/_relations";',
  );
  mkdirSync(join(root, 'packages/db/src/schema'), { recursive: true });
  writeFileSync(output, `// Generated by bun run auth:generate. Do not edit by hand.\n${source}`);
  const format = Bun.spawn([join(root, 'node_modules/.bin/oxfmt'), output], {
    cwd: root,
    stdout: 'inherit',
    stderr: 'inherit',
  });
  if ((await format.exited) !== 0) throw new Error('Auth schema formatting failed.');
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
