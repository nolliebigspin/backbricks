import { afterAll, expect, test } from 'bun:test';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import type { ConfiguredInstance } from '@backbricks/core';

import { formsCodegen } from './codegen.ts';
import { formsConfigSchema, type FormsConfig } from './config.ts';
import { formsTemplates } from './templates.ts';

const at = new Date('2026-11-09T00:00:00Z');
function instance(key: string, config: FormsConfig): ConfiguredInstance<FormsConfig> {
  return {
    id: `mod_${key}`,
    organizationId: 'org',
    projectId: 'prj',
    moduleType: 'forms',
    key,
    name: key,
    status: 'active',
    config,
    configVersion: 1,
    moduleVersion: 1,
    createdAt: at,
    updatedAt: at,
  };
}

const contact = formsTemplates({ files: true })['contact-en']!.config;
const application = formsTemplates({ files: true })['job-application-en']!.config;
const everything = formsConfigSchema.parse({
  fields: [
    { key: 'title', type: 'text', label: 'Title */ evil', required: true },
    { key: 'count', type: 'number', label: 'Count' },
    { key: 'agree', type: 'checkbox', label: 'Agree', required: true },
    {
      key: 'size',
      type: 'select',
      label: 'Size',
      required: true,
      options: [
        { value: 's', label: 'S' },
        { value: 'm-l', label: 'M/L' },
      ],
    },
    {
      key: 'extras',
      type: 'multiselect',
      label: 'Extras',
      options: [{ value: 'a', label: 'A' }],
    },
    { key: 'attachment', type: 'file', label: 'File', zone: 'docs' },
    { key: 'ok', type: 'consent', label: 'OK', text: 'Yes', version: '1' },
  ],
});

test('the snippet maps every field type and never emits owner text', () => {
  const code = formsCodegen(instance('everything', everything));
  expect(code).toContain(`"forms/everything": {`);
  expect(code).toContain(`"title": string;`);
  expect(code).toContain(`"count"?: number;`);
  expect(code).toContain(`"agree": boolean;`);
  expect(code).toContain(`"size": "s" | "m-l";`);
  expect(code).toContain(`"extras"?: Array<"a">;`);
  expect(code).toContain(`"attachment"?: string[];`);
  expect(code).toContain(`"ok": true;`);
  expect(code).not.toContain('evil');
});

const directories: string[] = [];
afterAll(async () => {
  await Promise.all(directories.map((path) => rm(path, { recursive: true, force: true })));
});

test('generated types for several forms compile together with TypeScript 7', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'forms-codegen-'));
  directories.push(directory);
  // Same assembly as the configuration service's types export: header plus one snippet per form.
  const generated =
    '// Generated by Backbricks. Do not edit.\n' +
    [
      formsCodegen(instance('contact', contact)),
      formsCodegen(instance('application', application)),
      formsCodegen(instance('everything', everything)),
    ].join('\n');
  const files = {
    'sdk.d.ts': `declare module '@backbricks/sdk' {
  export interface BackbricksSchema {}
  type FormKey = keyof BackbricksSchema & \`forms/\${string}\`;
  export function submit<K extends FormKey>(key: K, data: BackbricksSchema[K]): void;
}
`,
    'backbricks.gen.ts': generated,
    'usage.ts': `import { submit } from '@backbricks/sdk';

submit('forms/contact', { name: 'Ada', email: 'ada@example.com', message: 'Hi', privacy: true });
submit('forms/application', { name: 'Ada', email: 'a@b.c', position: 'Dev', cv: ['ref'], privacy: true });
submit('forms/everything', { title: 'x', agree: true, size: 'm-l', ok: true, extras: ['a'] });
// @ts-expect-error A required field is missing.
submit('forms/contact', { name: 'Ada', email: 'ada@example.com', privacy: true });
// @ts-expect-error Unknown fields are rejected.
submit('forms/contact', { name: 'Ada', email: 'a@b.c', message: 'Hi', privacy: true, extra: 1 });
// @ts-expect-error The value must be one of the options.
submit('forms/everything', { title: 'x', agree: true, size: 'xl', ok: true });
// @ts-expect-error Consent must be accepted.
submit('forms/everything', { title: 'x', agree: true, size: 's', ok: false });
// @ts-expect-error Unknown form.
submit('forms/missing', {});
`,
    'tsconfig.json': JSON.stringify({
      compilerOptions: {
        strict: true,
        noEmit: true,
        target: 'es2022',
        module: 'esnext',
        moduleResolution: 'bundler',
        skipLibCheck: false,
        types: [],
      },
      files: ['sdk.d.ts', 'backbricks.gen.ts', 'usage.ts'],
    }),
  };
  await Promise.all(
    Object.entries(files).map(([name, content]) => writeFile(join(directory, name), content)),
  );
  const tsc = join(dirname(Bun.resolveSync('typescript/package.json', import.meta.dir)), 'bin/tsc');
  const run = Bun.spawnSync([process.execPath, tsc, '--version']);
  expect(run.stdout.toString()).toStartWith('Version 7.');
  const result = Bun.spawnSync([process.execPath, tsc, '-p', directory]);
  expect(result.stdout.toString() + result.stderr.toString()).toBe('');
  expect(result.exitCode).toBe(0);
}, 60_000);
