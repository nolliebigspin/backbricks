import { AppError } from '../errors/app-error.ts';
import { MAX_PAGE_SIZE } from '../http/pagination.ts';
import { requireConfigAccess } from '../instances/permissions.ts';
import { validatedConfig, type InstanceDependencies } from '../instances/persistence.ts';
import type { InstanceService } from '../instances/service.ts';
import type { ModuleInstance } from '../platform/models.ts';
import type { TenantTransaction } from '../tenancy/tenant-context.ts';
import { configDigest, configPlanTokens } from './plan-token.ts';
import { planConfiguration } from './planner.ts';
import { configurationJsonSchema } from './schema-export.ts';
import {
  CONFIG_SCHEMA_ID,
  CONFIG_PLAN_TTL_MS,
  configChangeSchema,
  configDocumentSchema,
  type ConfigDocument,
} from './schemas.ts';

async function allInstances(tx: TenantTransaction) {
  const rows: ModuleInstance[] = [];
  let before: { createdAt: Date; id: string } | undefined;
  for (;;) {
    // oxlint-disable-next-line no-await-in-loop -- Each bounded page follows the preceding keyset cursor.
    const page = await tx.repositories.instances.list({ limit: MAX_PAGE_SIZE, before });
    rows.push(...page);
    const last = page.at(-1);
    if (page.length < MAX_PAGE_SIZE || !last) return rows;
    before = last;
  }
}

async function state(tx: TenantTransaction, lock = false) {
  requireConfigAccess(tx, 'read');
  if (!tx.context.projectId) throw new AppError('not_found');
  await tx.repositories.projects.get(tx.context.projectId, { lock });
  return allInstances(tx);
}
/** Read-only exports and principal/state/schema-bound plans; applying a plan is a separate write boundary. */
export function createConfigurationService(
  deps: InstanceDependencies & { appSecret: string; instances: InstanceService },
) {
  const tokens = configPlanTokens(deps.appSecret);
  function binding(tx: TenantTransaction, document: ConfigDocument, rows: ModuleInstance[]) {
    return configDigest({
      organization: tx.context.organizationId,
      project: tx.context.projectId,
      principal: tx.context.principal,
      desired: document,
      current: rows.map((row) => ({
        id: row.id,
        configVersion: row.configVersion,
        moduleVersion: row.moduleVersion,
        status: row.status,
      })),
      registry: deps.registry.modules.map((module) => ({
        type: module.type,
        version: module.moduleVersion,
        schema: module.configJsonSchema,
      })),
    });
  }
  return {
    schema: () => configurationJsonSchema(deps.registry),
    async types(tx: TenantTransaction) {
      const rows = await state(tx);
      return (
        '// Generated by Backbricks. Do not edit.\n' +
        rows
          .filter((row) => row.status !== 'archived')
          .flatMap((row) => {
            const module = deps.registry.get(row.moduleType);
            const code = module
              ? module.codegen({
                  ...row,
                  config: validatedConfig(module, row.config, row.moduleVersion),
                  moduleVersion: module.moduleVersion,
                })
              : null;
            return code ? [code] : [];
          })
          .join('\n')
      );
    },
    async apply(
      tx: TenantTransaction,
      input: unknown,
      planHash: string | undefined,
      requestId?: string,
    ) {
      requireConfigAccess(tx, 'write');
      const rows = await state(tx, true);
      const document = configDocumentSchema.parse(input);
      if (document.project !== tx.context.projectId) throw new AppError('not_found');
      const plan = planConfiguration(deps.registry, document, rows);
      if (!planHash)
        throw new AppError('conflict', { detail: 'Create a plan before applying configuration.' });
      tokens.verify(planHash, binding(tx, plan.document, rows), deps.clock.now().getTime());
      requireConfigAccess(tx, 'write', plan.destructive);
      const moduleOrder = new Map(
        deps.registry.modules.map((module, index) => [module.type, index]),
      );
      const operations = plan.operations.toSorted(
        (a, b) => (moduleOrder.get(a.moduleType) ?? 0) - (moduleOrder.get(b.moduleType) ?? 0),
      );
      for (const operation of operations) {
        const { moduleType, key, desired } = operation;
        if (operation.kind === 'archive') {
          const previous = rows.find((row) => row.moduleType === moduleType && row.key === key);
          if (!previous) throw new AppError('conflict');
          // oxlint-disable-next-line no-await-in-loop -- All operations are ordered in one caller transaction.
          await deps.instances.archive(tx, moduleType, key, previous.configVersion, requestId);
        } else {
          if (!desired) throw new AppError('internal_error');
          if (operation.kind === 'create') {
            // oxlint-disable-next-line no-await-in-loop -- The outer project lock spans every operation.
            await deps.instances.create(
              tx,
              moduleType,
              { key, name: desired.name, status: desired.status, config: desired.config },
              requestId,
            );
          } else {
            if (!desired.configVersion) throw new AppError('conflict');
            // oxlint-disable-next-line no-await-in-loop -- A later failure must roll back preceding operations.
            await deps.instances.replace(
              tx,
              moduleType,
              key,
              {
                name: desired.name,
                status: desired.status,
                config: desired.config,
                configVersion: desired.configVersion,
              },
              requestId,
            );
          }
        }
      }
      return {
        applied: true as const,
        changes: plan.operations.map((operation) => configChangeSchema.strip().parse(operation)),
        warnings: plan.warnings,
      };
    },
    async read(tx: TenantTransaction): Promise<ConfigDocument> {
      const rows = await state(tx);
      const modules: ConfigDocument['modules'] = {};
      for (const module of deps.registry.modules) {
        modules[module.resourceName.plural] = Object.fromEntries(
          rows
            .filter((row) => row.moduleType === module.type && row.status !== 'archived')
            .map((row) => [
              row.key,
              {
                name: row.name,
                status: row.status === 'paused' ? 'paused' : 'active',
                configVersion: row.configVersion,
                moduleVersion: module.moduleVersion,
                config: validatedConfig(module, row.config, row.moduleVersion),
              },
            ]),
        );
      }
      return configDocumentSchema.parse({
        $schema: CONFIG_SCHEMA_ID,
        project: tx.context.projectId,
        modules,
      });
    },
    async plan(tx: TenantTransaction, input: unknown) {
      const rows = await state(tx);
      const document = configDocumentSchema.parse(input);
      if (document.project !== tx.context.projectId) throw new AppError('not_found');
      const plan = planConfiguration(deps.registry, document, rows);
      const digest = binding(tx, plan.document, rows);
      const expiresAt = deps.clock.now().getTime() + CONFIG_PLAN_TTL_MS;
      return {
        changes: plan.operations.map((operation) => configChangeSchema.strip().parse(operation)),
        warnings: plan.warnings,
        destructive: plan.destructive,
        planHash: tokens.issue(digest, expiresAt),
        expiresAt: new Date(expiresAt).toISOString(),
      };
    },
  };
}
export type ConfigurationService = ReturnType<typeof createConfigurationService>;
